create function public.is_fewo_admin() returns boolean
  language sql stable set search_path = ''
  as $$ select lower(coalesce(auth.jwt() ->> 'email', '')) in ('a_t_f@outlook.de', 'fichter_alexander@icloud.com') $$;

create table public.fewo_wohnungen (
  id text primary key,
  sort integer not null default 0,
  name_de text not null, name_en text, name_fr text,
  text_de text, text_en text, text_fr text,
  gaeste integer, schlafzimmer integer, qm integer,
  preis_ab numeric, mindest_naechte integer,
  ausstattung text[] not null default '{}',
  fewo_url text,
  fotos text[] not null default '{}',
  updated_at timestamptz not null default now()
);

-- Nur Zeiträume, keine Gästenamen (die Tabelle ist öffentlich lesbar).
-- „bis“ ist der Abreisetag; er gilt auf der Seite als frei.
create table public.fewo_belegt (
  id bigint generated by default as identity primary key,
  wohnung text not null references public.fewo_wohnungen(id) on delete cascade,
  von date not null,
  bis date not null,
  quelle text not null default 'admin' check (quelle in ('admin', 'fewo')),
  check (bis > von)
);
create index on public.fewo_belegt (wohnung, bis);

alter table public.fewo_wohnungen enable row level security;
alter table public.fewo_belegt enable row level security;

create policy "FeWo: Wohnungen lesen" on public.fewo_wohnungen for select using (true);
create policy "FeWo: Wohnungen ändern" on public.fewo_wohnungen for update to authenticated using (public.is_fewo_admin()) with check (public.is_fewo_admin());
create policy "FeWo: Belegung lesen" on public.fewo_belegt for select using (true);
-- Einträge von FeWo-direkt (quelle = 'fewo') schreibt nur die Funktion fewo-ical.
create policy "FeWo: Belegung anlegen" on public.fewo_belegt for insert to authenticated with check (public.is_fewo_admin() and quelle = 'admin');
create policy "FeWo: Belegung löschen" on public.fewo_belegt for delete to authenticated using (public.is_fewo_admin() and quelle = 'admin');
grant select on public.fewo_wohnungen, public.fewo_belegt to anon, authenticated;
grant update on public.fewo_wohnungen to authenticated;
grant insert, delete on public.fewo_belegt to authenticated;

insert into storage.buckets (id, name, public) values ('fewo', 'fewo', true);
create policy "FeWo-Fotos lesen" on storage.objects for select using (bucket_id = 'fewo');
create policy "FeWo-Fotos hochladen" on storage.objects for insert to authenticated with check (bucket_id = 'fewo' and public.is_fewo_admin());
create policy "FeWo-Fotos löschen" on storage.objects for delete to authenticated using (bucket_id = 'fewo' and public.is_fewo_admin());

